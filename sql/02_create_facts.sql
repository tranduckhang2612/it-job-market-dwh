-- Fact_Job_Observation
-- Grain: một job nguồn tại một observation accepted (JobID + CrawlRunID)
CREATE TABLE IF NOT EXISTS dwh.fact_job_observation (
    observationkey      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observationdatekey  INTEGER NOT NULL REFERENCES dwh.dim_date (datekey),
    publisheddatekey    INTEGER NOT NULL REFERENCES dwh.dim_date (datekey),
    sourcekey           INTEGER NOT NULL REFERENCES dwh.dim_source (sourcekey),
    companykey          INTEGER NOT NULL REFERENCES dwh.dim_company (companykey),
    workmodekey         INTEGER NOT NULL REFERENCES dwh.dim_work_mode (workmodekey),
    salarycontextkey    INTEGER NOT NULL REFERENCES dwh.dim_salary_context (salarycontextkey),
    jobid               VARCHAR(100) NOT NULL,
    sourcejobid         VARCHAR(100),
    crawlrunid          VARCHAR(100) NOT NULL,
    observedat          TIMESTAMPTZ NOT NULL,
    locationtext        TEXT,
    experiencetext      TEXT,
    salarytext          TEXT,
    salarymin           NUMERIC(18, 2),
    salarymax           NUMERIC(18, 2),
    experienceminyears  NUMERIC(4, 1),
    experiencemaxyears  NUMERIC(4, 1),
    observationcount    SMALLINT NOT NULL DEFAULT 1,
    hasnumericsalary    SMALLINT NOT NULL,
    CONSTRAINT uq_fact_job_observation UNIQUE (jobid, crawlrunid),
    CONSTRAINT ck_fact_observationcount CHECK (observationcount = 1),
    CONSTRAINT ck_fact_hasnumericsalary CHECK (hasnumericsalary IN (0, 1)),
    CONSTRAINT ck_fact_salarymin CHECK (salarymin IS NULL OR salarymin > 0),
    CONSTRAINT ck_fact_salarymax CHECK (salarymax IS NULL OR salarymax > 0)
);

COMMIT;
