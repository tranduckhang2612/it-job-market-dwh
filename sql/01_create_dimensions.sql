-- =========================================================
-- 01_create_dimensions.sql
-- Tạo schema và 14 bảng Dimension cho DWH IT Job Market
-- =========================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS dwh;

-- 1. Dim_Date (DateKey dạng YYYYMMDD; 0/-1 cho Unknown/Invalid)
CREATE TABLE IF NOT EXISTS dwh.dim_date (
    datekey       INTEGER PRIMARY KEY,
    fulldate      DATE NOT NULL UNIQUE,
    day           SMALLINT NOT NULL CHECK (day BETWEEN 1 AND 31),
    month         SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    monthname     VARCHAR(20) NOT NULL,
    quarter       SMALLINT NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    year          SMALLINT NOT NULL,
    weekofyear    SMALLINT NOT NULL CHECK (weekofyear BETWEEN 1 AND 53),
    isweekend     BOOLEAN NOT NULL
);

-- 2. Dim_Source
CREATE TABLE IF NOT EXISTS dwh.dim_source (
    sourcekey     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sourcecode    VARCHAR(50) NOT NULL UNIQUE,
    sourcename    VARCHAR(100) NOT NULL
);

-- 3. Dim_Company
CREATE TABLE IF NOT EXISTS dwh.dim_company (
    companykey             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonicalcompanyname   VARCHAR(255) NOT NULL UNIQUE,
    industry               VARCHAR(100),
    companysize            VARCHAR(50)
);

-- 4. Dim_Work_Mode
CREATE TABLE IF NOT EXISTS dwh.dim_work_mode (
    workmodekey    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workmodecode   VARCHAR(50) NOT NULL UNIQUE,
    description    VARCHAR(100)
);

-- 5. Dim_Salary_Context
CREATE TABLE IF NOT EXISTS dwh.dim_salary_context (
    salarycontextkey INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency         VARCHAR(10) NOT NULL DEFAULT 'N/A',
    period           VARCHAR(20) NOT NULL DEFAULT 'N/A',
    basis            VARCHAR(20) NOT NULL DEFAULT 'N/A',
    status           VARCHAR(50) NOT NULL,
    CONSTRAINT uq_dim_salary_context UNIQUE (currency, period, basis, status)
);

-- 6. Dim_Job (SCD Type 2)
CREATE TABLE IF NOT EXISTS dwh.dim_job (
    jobkey          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jobid           VARCHAR(100) NOT NULL,
    sourcejobid     VARCHAR(100),
    joburl          TEXT,
    title           VARCHAR(500),
    description     TEXT,
    validfrom       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    validto         TIMESTAMPTZ,
    iscurrent       BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_dim_job_valid_dates CHECK (validto IS NULL OR validto > validfrom)
);
CREATE INDEX IF NOT EXISTS ix_dim_job_jobid ON dwh.dim_job (jobid);
CREATE UNIQUE INDEX IF NOT EXISTS uq_dim_job_current_jobid
    ON dwh.dim_job (jobid) WHERE iscurrent = TRUE;

-- 7. Dim_Role
CREATE TABLE IF NOT EXISTS dwh.dim_role (
    rolekey        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonicalrole  VARCHAR(100) NOT NULL UNIQUE,
    rolegroup      VARCHAR(100)
);

-- 8. Dim_Seniority
CREATE TABLE IF NOT EXISTS dwh.dim_seniority (
    senioritykey   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    senioritycode  VARCHAR(50) NOT NULL UNIQUE,
    description    VARCHAR(100)
);

-- 9. Dim_Location
CREATE TABLE IF NOT EXISTS dwh.dim_location (
    locationkey    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonicalcity  VARCHAR(100) NOT NULL UNIQUE,
    region         VARCHAR(100),
    country        VARCHAR(100) NOT NULL DEFAULT 'Vietnam'
);

-- 10. Dim_Skill
CREATE TABLE IF NOT EXISTS dwh.dim_skill (
    skillkey       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonicalskill VARCHAR(100) NOT NULL,
    category       VARCHAR(50),
    CONSTRAINT uq_dim_skill UNIQUE (canonicalskill, category)
);

-- 11. Dim_Knowledge
CREATE TABLE IF NOT EXISTS dwh.dim_knowledge (
    knowledgekey       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonicalknowledge VARCHAR(200) NOT NULL UNIQUE
);

-- 12. Dim_Education
CREATE TABLE IF NOT EXISTS dwh.dim_education (
    educationkey INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    degree       VARCHAR(100) NOT NULL DEFAULT 'Not Specified',
    major        VARCHAR(100) NOT NULL DEFAULT 'Not Specified',
    CONSTRAINT uq_dim_education UNIQUE (degree, major)
);

-- 13. Dim_Foreign_Language
CREATE TABLE IF NOT EXISTS dwh.dim_foreign_language (
    languagekey       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonicallanguage VARCHAR(100) NOT NULL UNIQUE
);

-- 14. Dim_Soft_Skill
CREATE TABLE IF NOT EXISTS dwh.dim_soft_skill (
    softskillkey       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonicalsoftskill VARCHAR(200) NOT NULL UNIQUE
);

COMMIT;
